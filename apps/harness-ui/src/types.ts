/**
 * Domain types for the TestRadius harness.
 *
 * These mirror the on-disk shapes produced by the Python harness exactly:
 *   - Plan reports:        reports/testradius-e2e-run-<id>.json
 *   - Execution reports:   reports/testradius-exec[-real]-<id>.json
 *   - Smoke reports:       reports/smoke-run-<id>.json
 *   - Evidence manifests:  artifacts/run-<id>/manifest.json
 *
 * Keep in sync with:
 *   - harness/runner/e2e_testradius.py        (plan reports)
 *   - harness/runner/execute_testradius_real.py (execution reports)
 *   - harness/evidence/capture.py             (manifests)
 *   - scripts/validate-shapes.mjs             (executable shape check)
 */

/* ------------------------------------------------------------------ */
/* Plans                                                               */
/* ------------------------------------------------------------------ */

/** Raw LLM output: a JSON string (sometimes fenced/escaped). */
export type PlanRaw = string;

/** Deterministic fallback returned when no API key is configured. */
export interface PlanFallback {
  plan: string[];
  note?: string;
  /** Populated when an LLM call failed and we fell back. */
  error?: string;
  fallback?: string[];
}

/** One test case inside a parsed plan (as generated by Gemini). */
export interface PlanTestCase {
  id: string;
  title: string;
  category?: string;
  preconditions?: string;
  steps: string[];
  expectedChecks: string[];
}

/** A fully parsed test plan. */
export interface TestPlan {
  testPlanTitle?: string;
  targetUrl?: string;
  version?: string;
  scope?: string[];
  testCases: PlanTestCase[];
}

/** reports/testradius-e2e-run-<id>.json */
export interface PlanReport {
  target: string;
  /** Raw plan: string (LLM output or JSON-escaped fallback object). */
  plan: PlanRaw;
  status: string;
  evidence: string;
}

/** List entry for the Plans view. */
export interface PlanSummary {
  id: string;
  target: string;
  status: string;
  createdAt?: string;
}

/* ------------------------------------------------------------------ */
/* Executions (runs)                                                   */
/* ------------------------------------------------------------------ */

/** Result of one executed expectedCheck. */
export interface AssertionResult {
  check: string;
  /** "RECORDED" today; "PASS" | "FAIL" once real assertions land (H005.x). */
  status: string;
}

/** One executed test case. `screenshots`/`assertions` only exist in real runs. */
export interface ExecutedTestCase {
  id: string;
  title: string;
  category?: string;
  preconditions?: string;
  /** "EXECUTED" | "ERROR" (real) or "RECORDED_FROM_PLAN" (recorded). */
  status: string;
  steps: string[];
  expectedChecks: string[];
  screenshots?: string[];
  assertions?: AssertionResult[];
  error?: string;
}

/** reports/testradius-exec[-real]-<id>.json */
export interface ExecutionReport {
  source_plan?: string;
  target: string;
  test_plan_title?: string | null;
  /** "real_browser_sandbox" for real runs; absent for recorded runs. */
  mode?: string;
  executed: ExecutedTestCase[];
  count: number;
  status: string;
  /** Absolute or relative path to the .webm recording (real runs). */
  video?: string | null;
  /** Path to trace.json (real runs). */
  trace?: string | null;
  evidence: string;
}

/** List entry for the Runs view. */
export interface RunSummary {
  id: string;
  target: string;
  status: string;
  count: number;
  evidence: string;
  createdAt?: string;
  /** True once the user has approved the plan (checkpoint passed). */
  approved?: boolean;
  /** ID of the generated test plan for this run. */
  planId?: string;
}

/* ------------------------------------------------------------------ */
/* Run creation                                                        */
/* ------------------------------------------------------------------ */

/** Gemini models selectable in the New Run form (mirrors harness config). */
export type GeminiModel =
  | "gemini-2.5-flash"
  | "gemini-2.5-flash-lite"
  | "gemini-2.0-flash";

/** Input for POST /api/runs — the New Run form payload. */
export interface CreateRunInput {
  target: string;
  goal: string;
  /** Optional ticket/context reference (e.g. "T-1" or bundle path). */
  context?: string;
  model: GeminiModel;
}

/* ------------------------------------------------------------------ */
/* Evidence                                                            */
/* ------------------------------------------------------------------ */

/** Artifact kinds recorded by harness/evidence/capture.py. */
export type EvidenceArtifactType =
  | "screenshot"
  | "console"
  | "network"
  | "trace"
  | (string & {});

export interface EvidenceArtifact {
  type: EvidenceArtifactType;
  path: string;
}

/** artifacts/run-<id>/manifest.json */
export interface EvidenceManifest {
  run_id: string;
  artifacts: EvidenceArtifact[];
}

/* ------------------------------------------------------------------ */
/* Smoke runs (local sandbox flow)                                     */
/* ------------------------------------------------------------------ */

/** reports/smoke-run-<id>.json */
export interface SmokeReport {
  ticket: string;
  context: string;
  status: string;
  evidence: string;
}
